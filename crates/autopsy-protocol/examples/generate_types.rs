use autopsy_protocol::*;
use std::env;
use std::fs;
use std::path::PathBuf;

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let workspace_root = env::var("CARGO_MANIFEST_DIR")
        .map(PathBuf::from)
        .unwrap_or_else(|_| PathBuf::from("."))
        .parent()
        .unwrap()
        .parent()
        .unwrap()
        .to_path_buf();
    
    println!("Workspace root: {:?}", workspace_root);
    
    // Generate command schema JSON
    let schema = generate_schema();
    let schema_path = workspace_root.join("schemas/command.schema.json");
    fs::write(&schema_path, serde_json::to_string_pretty(&schema)?)?;
    println!("Generated command schema at {:?}", schema_path);
    
    // Generate TypeScript types for web
    let web_types_dir = workspace_root.join("apps/web/src/types");
    fs::create_dir_all(&web_types_dir)?;
    write_command_typescript_definitions(&web_types_dir)?;
    println!("Generated web command types at {:?}", web_types_dir);
    
    // Generate TypeScript types for electron
    let electron_types_dir = workspace_root.join("apps/desktop-electron/src/types");
    fs::create_dir_all(&electron_types_dir)?;
    write_command_typescript_definitions(&electron_types_dir)?;
    println!("Generated electron command types at {:?}", electron_types_dir);
    
    Ok(())
}

fn write_command_typescript_definitions(output_dir: &PathBuf) -> Result<(), Box<dyn std::error::Error>> {
    let ts = generate_command_typescript_types();
    let output_path = output_dir.join("command-protocol.d.ts");
    fs::write(output_path, ts)?;
    Ok(())
}

