//! TypeScript type generation for the EvidenceEnvelope
//!
//! This module generates TypeScript type definitions from the Rust types
//! to ensure all clients (Web, Electron) use the exact same envelope shape.

use std::fs;
use std::path::Path;

use serde_json::Value;
use schemars::schema_for;

use crate::EvidenceEnvelope;

/// Generate TypeScript definitions for the envelope
pub fn generate_typescript_types() -> String {
    let _schema = schema_for!(EvidenceEnvelope);
    // Schema used for validation; we build TypeScript directly for precision
    
    // Build TypeScript from the schema
    let mut ts = String::new();
    
    ts.push_str("// AUTOGENERATED - DO NOT EDIT\n");
    ts.push_str("// Generated from autopsy-envelope crate via schemars\n");
    ts.push_str("// Source: crates/autopsy-envelope/src/lib.rs\n\n");
    
    ts.push_str("export type Verdict = \n");
    ts.push_str("  | 'PASS'\n");
    ts.push_str("  | 'FAIL'\n");
    ts.push_str("  | 'WARN'\n");
    ts.push_str("  | 'PARTIAL'\n");
    ts.push_str("  | 'UNKNOWN'\n");
    ts.push_str("  | 'ERROR'\n");
    ts.push_str("  | 'UNAVAILABLE';\n\n");
    
    ts.push_str("export type CoverageState = \n");
    ts.push_str("  | 'verified'\n");
    ts.push_str("  | 'partial'\n");
    ts.push_str("  | 'unknown'\n");
    ts.push_str("  | 'unavailable'\n");
    ts.push_str("  | 'error';\n\n");
    
    ts.push_str("export interface EvidenceReceipt {\n");
    ts.push_str("  algorithm: string;\n");
    ts.push_str("  digest: string;\n");
    ts.push_str("  source: string;\n");
    ts.push_str("  test_reference: string;\n");
    ts.push_str("  timestamp: string; // ISO 8601\n");
    ts.push_str("  engine_version: string;\n");
    ts.push_str("  adapter_versions: Record<string, string>;\n");
    ts.push_str("}\n\n");
    
    ts.push_str("export interface EvidenceEnvelope {\n");
    ts.push_str("  operation_id: string;\n");
    ts.push_str("  repository_id: string | null;\n");
    ts.push_str("  canonical_path: string | null;\n");
    ts.push_str("  snapshot_id: string | null;\n");
    ts.push_str("  session_id: string | null;\n");
    ts.push_str("  workflow_id: string | null;\n");
    ts.push_str("  event_seq: number | null;\n");
    ts.push_str("  verdict: Verdict;\n");
    ts.push_str("  coverage_state: CoverageState;\n");
    ts.push_str("  warnings: string[];\n");
    ts.push_str("  latency_ms: number | null;\n");
    ts.push_str("  blake3_digest: string;\n");
    ts.push_str("  evidence_receipt: EvidenceReceipt;\n");
    ts.push_str("  // Command-specific payload (flattened)\n");
    ts.push_str("  [key: string]: unknown;\n");
    ts.push_str("}\n\n");
    
    // Helper functions for building envelopes
    ts.push_str("/**\n");
    ts.push_str(" * Build a successful envelope (PASS + VERIFIED)\n");
    ts.push_str(" */\n");
    ts.push_str("export function buildSuccessEnvelope(\n");
    ts.push_str("  operationId: string,\n");
    ts.push_str("  engineVersion: string,\n");
    ts.push_str("  payload: Record<string, unknown>,\n");
    ts.push_str("  repositoryId?: string,\n");
    ts.push_str("  snapshotId?: string\n");
    ts.push_str("): EvidenceEnvelope {\n");
    ts.push_str("  const canonical = JSON.stringify(payload);\n");
    ts.push_str("  const blake3Digest = computeBlake3(canonical);\n");
    ts.push_str("  return {\n");
    ts.push_str("    operation_id: operationId,\n");
    ts.push_str("    repository_id: repositoryId ?? null,\n");
    ts.push_str("    canonical_path: null,\n");
    ts.push_str("    snapshot_id: snapshotId ?? null,\n");
    ts.push_str("    session_id: null,\n");
    ts.push_str("    workflow_id: null,\n");
    ts.push_str("    event_seq: null,\n");
    ts.push_str("    verdict: 'PASS',\n");
    ts.push_str("    coverage_state: 'verified',\n");
    ts.push_str("    warnings: [],\n");
    ts.push_str("    latency_ms: null,\n");
    ts.push_str("    blake3_digest: `blake3:${blake3Digest}`,\n");
    ts.push_str("    evidence_receipt: {\n");
    ts.push_str("      algorithm: 'BLAKE3',\n");
    ts.push_str("      digest: `blake3:${blake3Digest}`,\n");
    ts.push_str("      source: 'daemon response',\n");
    ts.push_str("      test_reference: 'schemas/evidence-envelope.schema.json',\n");
    ts.push_str("      timestamp: new Date().toISOString(),\n");
    ts.push_str("      engine_version: engineVersion,\n");
    ts.push_str("      adapter_versions: {},\n");
    ts.push_str("    },\n");
    ts.push_str("    ...payload,\n");
    ts.push_str("  };\n");
    ts.push_str("}\n\n");
    
    ts.push_str("/**\n");
    ts.push_str(" * Verify an envelope's BLAKE3 digest\n");
    ts.push_str(" */\n");
    ts.push_str("export function verifyEnvelope(envelope: EvidenceEnvelope): boolean {\n");
    ts.push_str("  const canonical = JSON.stringify(stripEnvelopeMeta(envelope));\n");
    ts.push_str("  const expectedDigest = `blake3:${computeBlake3(canonical)}`;\n");
    ts.push_str("  return envelope.blake3_digest === expectedDigest;\n");
    ts.push_str("}\n\n");
    
    ts.push_str("function stripEnvelopeMeta(env: EvidenceEnvelope): Record<string, unknown> {\n");
    ts.push_str("  const { operation_id, repository_id, canonical_path, snapshot_id, session_id,\n");
    ts.push_str("    workflow_id, event_seq, verdict, coverage_state, warnings, latency_ms,\n");
    ts.push_str("    blake3_digest, evidence_receipt, ...payload } = env;\n");
    ts.push_str("  return payload;\n");
    ts.push_str("}\n\n");
    
    ts.push_str("// BLAKE3 computation (requires @noble/hashes or similar)\n");
    ts.push_str("function computeBlake3(input: string): string {\n");
    ts.push_str("  // Implementation would use @noble/hashes/blake3\n");
    ts.push_str("  // This is a placeholder - actual implementation in verify.ts\n");
    ts.push_str("  return 'placeholder';\n");
    ts.push_str("}\n");
    
    ts
}

/// Write TypeScript definitions to file
pub fn write_typescript_definitions(output_dir: &Path) -> Result<(), Box<dyn std::error::Error>> {
    let ts_content = generate_typescript_types();
    let output_path = output_dir.join("evidence-envelope.d.ts");
    fs::write(output_path, ts_content)?;
    Ok(())
}

/// Generate JSON Schema for the envelope
pub fn generate_envelope_json_schema() -> Value {
    let schema = schema_for!(EvidenceEnvelope);
    serde_json::to_value(&schema).unwrap()
}

/// Write JSON Schema to file
pub fn write_envelope_json_schema(output_dir: &Path) -> Result<(), Box<dyn std::error::Error>> {
    let schema = generate_envelope_json_schema();
    let output_path = output_dir.join("evidence-envelope.schema.json");
    fs::write(output_path, serde_json::to_string_pretty(&schema)?)?;
    Ok(())
}

